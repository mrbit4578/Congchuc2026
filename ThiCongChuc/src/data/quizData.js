export function getQuestionsByCategory(category) {
  if (category === "all") return quizQuestions;
  return quizQuestions.filter(q => q.category === category);
}

export function getQuestionsBySubcategory(subcategory) {
  return quizQuestions.filter(q => q.subcategory === subcategory);
}

export function getSubcategories() {
  const subs = [...new Set(quizQuestions.map(q => q.subcategory))];
  return subs;
}

export function getRandomQuestions(count, category = "all") {
  const pool = category === "all" ? [...quizQuestions] : quizQuestions.filter(q => q.category === category);
  const shuffled = pool.sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
